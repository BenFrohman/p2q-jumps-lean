"""Untrusted generator: writes the Lean kernel certificate modules for the H2 checker
`H2K.scan` (P2qJumps.H2K.Defs) from the data of gen_data.py.
usage: gen_kernel.py DATA.jsonl LO B STEP PER_FILE OUTDIR
Each theorem `cert_<lo>` states `scan hi (hi + 1 - lo) lo [items] = true` for [lo, hi];
the ranges tile [LO, B]. The generator is not trusted."""
import json, sys, os
from sympy import factorint
data_path, LO, B, STEP, PER, outdir = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]), int(sys.argv[5]), sys.argv[6]
pdata = {}
for l in open(data_path):
    r = json.loads(l); pdata[r[0]] = r
def pm(b, e, m): return pow(b, e, m)
def comp(m):
    return (m % 2 == 0 and 2 < m) or (m % 3 == 0 and 3 < m) or (m % 5 == 0 and 5 < m) or \
        (m % 7 == 0 and 7 < m) or (2 < m < 2097152 and pow(2, m - 1, m) != 1)
def instr(i):
    if i[0] == "s": return f".s {i[1]}"
    return f".b {i[1]} {i[2]} [{', '.join(map(str, i[3]))}]"
def item(m):
    if m in pdata:
        p, a2, a3, ins, es = pdata[m]
        return f".pr {p} {a2} {a3} [{', '.join(instr(i) for i in ins)}] [{', '.join(map(str, es))}]"
    if comp(m): return None
    d = min(factorint(m))
    assert d < m, m
    return f".c {m} {d}"
ranges = []
lo = LO
while lo <= B:
    hi = min(lo + STEP - 1, B); ranges.append((lo, hi)); lo = hi + 1
HDR = """/-
Copyright (c) 2026 Benjamin Stanley Frohman. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Benjamin Stanley Frohman
-/

import P2qJumps.H2K.Defs

/-!
# P2qJumps.H2K.Kernel.{name}

Kernel certificates (`decide +kernel`, no `native_decide`) for the H2 checker `scan`
(`P2qJumps.H2K.Defs`), ranges {rlo}..{rhi}. Generated by `scripts/h2/gen_kernel.py`; the
generator is not trusted, every statement below is checked by the Lean kernel.
-/

namespace P2qJumps

namespace H2K

"""
os.makedirs(outdir, exist_ok=True)
names = []; filelems = []
for fi in range(0, len(ranges), PER):
    rs = ranges[fi:fi + PER]
    name = f"C{fi // PER:03d}"; names.append(name)
    body = HDR.format(name=name, rlo=rs[0][0], rhi=rs[-1][1])
    for lo, hi in rs:
        its = [x for x in (item(m) for m in range(lo, hi + 1)) if x is not None]
        body += f"/-- Kernel certificate for `{lo} ≤ m ≤ {hi}`. -/\ntheorem cert_{lo} :\n    scan {hi} {hi + 1 - lo} {lo}\n      [{', '.join(its)}] = true := by\n  decide +kernel\n\n"
    body += "end H2K\n\nend P2qJumps\n"
    open(os.path.join(outdir, name + ".lean"), "w").write(body)
    filelems.append((rs, name))
glue = """/-
Copyright (c) 2026 Benjamin Stanley Frohman. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Benjamin Stanley Frohman
-/

import P2qJumps.H2K.Sound
""" + "".join(f"import P2qJumps.H2K.Kernel.{n}\n" for n in names) + f"""
/-!
# P2qJumps.H2K.Kernel

Assembles the kernel certificates `cert_<lo>` (ranges tiling `[{LO}, {B}]`) with `scan_sound`.
Generated by `scripts/h2/gen_kernel.py`.
-/

namespace P2qJumps

namespace H2K

"""
for rs, name in filelems:
    flo, fhi = rs[0][0], rs[-1][1]
    glue += f"/-- Every prime `p` with `{flo} ≤ p ≤ {fhi}` is `GoodP`. -/\ntheorem good_{name} (p : ℕ) (hlo : {flo} ≤ p) (hhi : p ≤ {fhi}) (hp : p.Prime) : GoodP p := by\n"
    prev = "hlo"
    for lo, hi in rs[:-1]:
        glue += f"  by_cases hc{lo} : p ≤ {hi}\n  · exact scan_sound {hi} _ _ _ cert_{lo} p {prev} hc{lo} hp\n"
        prev = f"(Nat.lt_of_not_le hc{lo})"
    lo, hi = rs[-1]
    glue += f"  exact scan_sound {hi} _ _ _ cert_{lo} p {prev} hhi hp\n\n"
glue += f"""/-- Every prime `{LO} ≤ p ≤ {B}` is `GoodP`. -/
theorem good_upto (p : ℕ) (h5 : {LO} ≤ p) (hB : p ≤ {B}) (hp : p.Prime) : GoodP p := by
"""
prev = "h5"
for rs, nm in filelems[:-1]:
    lo, hi = rs[0][0], rs[-1][1]
    glue += f"  by_cases hf{lo} : p ≤ {hi}\n  · exact good_{nm} p {prev} hf{lo} hp\n"
    prev = f"(Nat.lt_of_not_le hf{lo})"
rs, nm = filelems[-1]
glue += f"  exact good_{nm} p {prev} hB hp\n\nend H2K\n\nend P2qJumps\n"
open(os.path.join(os.path.dirname(outdir.rstrip("/")), "Kernel.lean"), "w").write(glue)
json.dump({"ranges": ranges, "files": [[n, rs[0][0], rs[-1][1]] for rs, n in filelems]},
          open(os.environ.get("RANGES_OUT", "scripts/h2/ranges.json"), "w"))
print(len(ranges), len(names))
