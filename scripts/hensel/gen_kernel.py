"""Untrusted generator: writes Lean kernel certificate modules for the Hensel checker.

usage: gen_kernel.py DATA.jsonl B STEP PER_FILE OUTDIR
Each theorem `cert_<lo>` states `scan hi (hi + 1 - lo) lo [items] = true` for [lo, hi] and is
proved by `decide +kernel`. Ranges tile [5, B].
"""
import json, sys, os
data_path, B, STEP, PER, outdir = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), int(sys.argv[4]), sys.argv[5]
items = [json.loads(l) for l in open(data_path)]
def lean(e):
    k = e[0]
    return f".{k} " + " ".join(str(v) for v in e[1:])
ranges = []
lo = int(os.environ.get("LO", "5"))
while lo <= B:
    hi = min(lo + STEP - 1, B); ranges.append((lo, hi)); lo = hi + 1
HDR = """/-
Copyright (c) 2026 Benjamin Stanley Frohman. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Benjamin Stanley Frohman
-/

import P2qJumps.Hensel.Defs

/-!
# P2qJumps.Hensel.Kernel.{name}

Kernel certificates (`decide +kernel`, no `native_decide`) for the Hensel checker `scan`
(`P2qJumps.Hensel.Defs`), ranges {rlo}..{rhi}. Generated by `scripts/hensel/gen_kernel.py`; the
generator is not trusted, every statement below is checked by the Lean kernel.
-/

namespace P2qJumps

namespace Hensel

"""
os.makedirs(outdir, exist_ok=True)
names = []
filelems = []
idx = 0
for fi in range(0, len(ranges), PER):
    rs = ranges[fi:fi + PER]
    name = f"C{fi // PER:03d}"
    names.append(name)
    body = HDR.format(name=name, rlo=rs[0][0], rhi=rs[-1][1])
    for lo, hi in rs:
        its = []
        while idx < len(items) and items[idx][1] <= hi:
            assert items[idx][1] >= lo
            its.append(lean(items[idx])); idx += 1
        lst = "[" + ", ".join(its) + "]"
        body += f"/-- Kernel certificate for `{lo} ≤ m ≤ {hi}`. -/\ntheorem cert_{lo} :\n    scan {hi} {hi + 1 - lo} {lo}\n      {lst} = true := by\n  decide +kernel\n\n"
    filelems.append((rs, name))
    body += "end Hensel\n\nend P2qJumps\n"
    open(os.path.join(outdir, name + ".lean"), "w").write(body)
assert idx == len(items)
glue = """/-
Copyright (c) 2026 Benjamin Stanley Frohman. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Benjamin Stanley Frohman
-/

import P2qJumps.Hensel.Sound
""" + "".join(f"import P2qJumps.Hensel.Kernel.{n}\n" for n in names) + f"""
/-!
# P2qJumps.Hensel.Kernel

Assembles the kernel certificates `cert_<lo>` (ranges tiling `[5, {B}]`) with `scan_sound`.
Generated by `scripts/hensel/gen_kernel.py`.
-/

namespace P2qJumps

namespace Hensel

"""
for rs, name in filelems:
    flo, fhi = rs[0][0], rs[-1][1]
    glue += f"/-- Every prime `5 ≤ r` with `{flo} ≤ r ≤ {fhi}` is `Good`. -/\ntheorem good_{name} (r : ℕ) (hlo : {flo} ≤ r) (hhi : r ≤ {fhi}) (hr : r.Prime) (h5 : 5 ≤ r) : Good r := by\n"
    prev = "hlo"
    for lo, hi in rs[:-1]:
        glue += f"  by_cases hc{lo} : r ≤ {hi}\n  · exact scan_sound {hi} _ _ _ cert_{lo} r {prev} hc{lo} hr h5\n"
        prev = f"(Nat.lt_of_not_le hc{lo})"
    lo, hi = rs[-1]
    glue += f"  exact scan_sound {hi} _ _ _ cert_{lo} r {prev} hhi hr h5\n\n"
glue += f"""/-- Every prime `5 ≤ r ≤ {B}` is `Good`. -/
theorem good_upto (r : ℕ) (h5 : 5 ≤ r) (hB : r ≤ {B}) (hr : r.Prime) : Good r := by
"""
franges = []
for fi in range(0, len(ranges), PER):
    rs = ranges[fi:fi + PER]; franges.append((rs[0][0], rs[-1][1], f"C{fi // PER:03d}"))
prev = "h5"
for lo, hi, nm in franges[:-1]:
    glue += f"  by_cases hf{lo} : r ≤ {hi}\n  · exact good_{nm} r {prev} hf{lo} hr h5\n"
    prev = f"(Nat.lt_of_not_le hf{lo})"
lo, hi, nm = franges[-1]
glue += f"  exact good_{nm} r {prev} hB hr h5\n\nend Hensel\n\nend P2qJumps\n"
open(os.path.join(os.path.dirname(outdir.rstrip("/")), "Kernel.lean"), "w").write(glue)
json.dump({"ranges": ranges, "files": names, "per_file": PER}, open(os.environ.get("RANGES_OUT", "scripts/hensel/ranges.json"), "w"))
print(len(ranges), "theorems in", len(names), "files")
