"""Generate P2qJumps/P7Kernel/*.lean: split kernel certificates for the p = 7 descent checker
`desc` (P2qJumps/P7Defs.lean). Usage: python3 scripts/p7/gen_kernel.py 400 . (from the repo root).
Not trusted: every generated statement is checked by the Lean kernel (decide +kernel)."""
import math, sys
sys.setrecursionlimit(10000)
def okR(b,h,s,m,r): return 7*h*(r-1)**m < 6*b*r**m and 57*b*r**m < 49*s*(r+1)**m
def kind(b,h,s,last,m):
    if m==2: return 'term'
    if m<2: return 'false'
    if 1<=6*b-7*h: return 'true'
    if 1<=49*s-57*b: return 'last'
    if 6*b-7*h==0 or 49*s-57*b==0: return 'true'
    if 1<=342*b*b-343*h*s: return 'true'
    return 'loop'
def children(b,h,s,last,m):
    r=max(last+1,11); out=[]; F=300
    while F>0:
        if not okR(b,h,s,m,r): return out, r
        if math.gcd(r,210)==1: out.append(r)
        r+=1; F-=1
    raise Exception('fuel')
def size(b,h,s,last,m):
    k=kind(b,h,s,last,m)
    if k!='loop': return 1
    ch,_=children(b,h,s,last,m)
    return 1+sum(size(b*r,h*(r-1),s*(r+1),r,m-1) for r in ch)
import os, re
T=100; MT=int(sys.argv[1]) if len(sys.argv)>1 else 400
HDR="""/-
Copyright (c) 2026 Benjamin Stanley Frohman. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Benjamin Stanley Frohman
-/

"""
mods={}   # modname -> [imports set, list of theorem texts, doc]
def modfor(name): return "K"+name[len("cert"):]  # cert9_29 -> K9_29
def node(name, fuel, bE,hE,sE,lastE,mE, b,h,s,last,m, doc, mod):
    stmt=f"desc {fuel} {bE} {hE} {sE} {lastE} {mE}"
    if kind(b,h,s,last,m)!='loop' or size(b,h,s,last,m)<=T:
        mods[mod][1].append(f"/-- {doc} -/\ntheorem {name} :\n    {stmt} = true := by\n  decide +kernel\n"); return
    ch,R=children(b,h,s,last,m)
    r0=max(last+1,11)
    for r in ch:
        rc=f"(({r} : ℕ) : ℤ)"
        cn=f"{name}_{r}"
        cb,chh,cs=b*r,h*(r-1),s*(r+1)
        if size(cb,chh,cs,r,m-1)>MT//4 and size(b,h,s,last,m)>MT:
            cm=modfor(cn); mods[cm]=[set(),[],f"{doc}, next prime `{r}`"]; mods[cm][0].add("P2qJumps.P7Kernel.Lemmas")
            mods[mod][0].add("P2qJumps.P7Kernel."+cm)
        else: cm=mod
        node(cn, fuel-1, f"({bE} * {rc})", f"({hE} * ({rc} - 1))", f"({sE} * ({rc} + 1))",
             f"{r}", f"({mE} - 1)", cb,chh,cs, r, m-1, f"{doc}, next prime `{r}`", cm)
    lines=[f"/-- {doc}: split over the next prime `r ∈ [{r0}, {R})` prime to `210`. -/",
           f"theorem {name} :\n    {stmt} = true := by",
           f"  refine (desc_split (fuel := {fuel-1}) (by decide +kernel)).trans ?_",
           f"  refine loopR_start (r0 := {r0}) (by decide) ?_"]
    F=300
    for r in range(r0,R):
        hc = f"(fun _ => {name}_{r})" if r in ch else "(fun hg => absurd hg (by decide +kernel))"
        lines.append(f"  refine loopR_step (F := {F-1}) (r := {r}) (by decide +kernel) {hc} ?_"); F-=1
    lines.append(f"  exact loopR_stop (F := {F-1}) (r := {R}) (by decide +kernel)")
    mods[mod][1].append("\n".join(lines)+"\n")
for k in (7,8,9):
    m=f"K{k}"; mods[m]=[{"P2qJumps.P7Kernel.Lemmas"},[],f"`ω(N) = {k}`"]
    node(f"cert{k}", 10, "1","1","1","10",f"{k}", 1,1,1,10,k, f"Kernel certificate, `ω(N) = {k}`", m)
out=sys.argv[2]
os.makedirs(out+"/P7Kernel",exist_ok=True)
for m,(imps,ths,doc) in mods.items():
    body=HDR+"".join(f"import {i}\n" for i in sorted(imps))+f"""
/-!
# P2qJumps.P7Kernel.{m}

Kernel certificates (`decide +kernel`, no `native_decide`) for the `p = 7` descent checker `desc`
(`P2qJumps.P7Defs`), subtree: {doc}. Generated by `scripts/p7/gen_kernel.py`; the generator is not
trusted, every statement below is checked by the Lean kernel.
-/

namespace P2qJumps

namespace P7Cert

"""+"\n".join(reversed(ths[::-1]))+"\nend P7Cert\n\nend P2qJumps\n"
    open(f"{out}/P7Kernel/{m}.lean","w").write(body)
print(len(mods), {m:len(v[1]) for m,v in mods.items()})
