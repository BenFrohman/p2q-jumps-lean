"""Untrusted generator: writes the Lean kernel certificate modules for the omega(N) >= 4 checker
`chkP` (P2qJumps.Omega4Q.Defs) from the chunk plan of plan.py.
usage: gen_kernel.py PLAN.json PER_FILE OUTDIR
Each theorem `c_<p>_<lo>` states `chkP p lo hi = true` and is proved by `decide +kernel`.
The ranges of each p tile [3 p^2, 10^6]; the generator is not trusted."""
import json, sys, os
plan = json.load(open(sys.argv[1])); PER = int(sys.argv[2]); outdir = sys.argv[3]
Q = 10**6
HDR = """/-
Copyright (c) 2026 Benjamin Stanley Frohman. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Benjamin Stanley Frohman
-/

import P2qJumps.Omega4Q.Defs

/-!
# P2qJumps.Omega4Q.Kernel.{name}

Kernel certificates (`decide +kernel`, no `native_decide`) for the checker `chkP`
(`P2qJumps.Omega4Q.Defs`). Generated by `scripts/omega4q/gen_kernel.py`; the generator is not
trusted, every statement below is checked by the Lean kernel.
-/

namespace P2qJumps

namespace Omega4Q

"""
ps = sorted(int(p) for p in plan)
chunks = []
for p in ps:
    rs = plan[str(p)]
    assert rs[0][0] == 3*p*p and rs[-1][1] == Q
    for (a, b), (c, _) in zip(rs, rs[1:]): assert c == b + 1
    for a, b in rs: chunks.append((p, a, b))
os.makedirs(outdir, exist_ok=True)
names = []
for fi in range(0, len(chunks), PER):
    name = f"C{fi // PER:03d}"; names.append(name)
    body = HDR.format(name=name)
    for p, a, b in chunks[fi:fi + PER]:
        body += f"theorem c_{p}_{a} : chkP {p} {a} {b} = true := by\n  decide +kernel\n\n"
    body += "end Omega4Q\n\nend P2qJumps\n"
    open(os.path.join(outdir, name + ".lean"), "w").write(body)
glue = """/-
Copyright (c) 2026 Benjamin Stanley Frohman. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Benjamin Stanley Frohman
-/

import P2qJumps.Omega4Q.Sound
""" + "".join(f"import P2qJumps.Omega4Q.Kernel.{n}\n" for n in names) + """
/-!
# P2qJumps.Omega4Q.Kernel

Assembles the kernel certificates `c_<p>_<lo>` with `chkP_sound`: for every prime `5 ≤ p ≤ 577`
and every odd `q` with `3 p^2 ≤ q ≤ 10^6` and `16 ∣ p (p - 1) (q - 1) + 12`, `chkQ` passes.
Generated by `scripts/omega4q/gen_kernel.py`.
-/

namespace P2qJumps

namespace Omega4Q

"""
for p in ps:
    rs = plan[str(p)]
    glue += (f"theorem okp_{p} (q : ℕ) (hlo : {3*p*p} ≤ q) (hhi : q ≤ 1000000) (hqo : q % 2 = 1)\n"
             f"    (h16 : ({p} * ({p} - 1) * (q - 1) + 12) % 16 = 0) :\n"
             f"    chkQ {p} (fct {p}) (fct 1000) q = true := by\n")
    for a, b in rs[:-1]:
        glue += (f"  by_cases hc{a} : q ≤ {b}\n"
                 f"  · exact chkP_sound c_{p}_{a} q (by omega) hc{a} hqo h16\n"
                 f"  replace hlo : {b + 1} ≤ q := by omega\n")
    a, b = rs[-1]
    glue += f"  exact chkP_sound c_{p}_{a} q hlo hhi hqo h16\n\n"
plist = ", ".join(map(str, ps))
glue += f"""/-- A Boolean primality test by trial division. -/
def isPr (n : ℕ) : Bool := (List.range n).all fun m => m < 2 || n % m != 0

lemma isPr_of_prime {{n : ℕ}} (hn : n.Prime) : isPr n = true := by
  unfold isPr
  rw [List.all_eq_true]
  intro m hm
  rw [List.mem_range] at hm
  simp only [Bool.or_eq_true, decide_eq_true_eq, bne_iff_ne, ne_eq]
  by_contra hcon
  push_neg at hcon
  have hdvd : m ∣ n := Nat.dvd_of_mod_eq_zero hcon.2
  rcases hn.eq_one_or_self_of_dvd m hdvd with h | h <;> omega

/-- The primes in `[5, 577]`. -/
theorem primes_cover : ∀ p, p < 578 → 5 ≤ p → isPr p = true →
    p ∈ ([{plist}] : List ℕ) := by
  decide +kernel

/-- **Kernel coverage.** -/
theorem chkQ_all {{p q : ℕ}} (hp : p.Prime) (hp5 : 5 ≤ p) (hp577 : p ≤ 577) (hlo : 3 * p * p ≤ q)
    (hhi : q ≤ 1000000) (hqo : q % 2 = 1) (h16 : (p * (p - 1) * (q - 1) + 12) % 16 = 0) :
    chkQ p (fct p) (fct 1000) q = true := by
  have hmem := primes_cover p (by omega) hp5 (isPr_of_prime hp)
  simp only [List.mem_cons, List.not_mem_nil, or_false] at hmem
  obtain {" | ".join("rfl" for _ in ps)} := hmem
"""
for p in ps:
    glue += f"  · exact okp_{p} q (by omega) hhi hqo h16\n"
glue += "\nend Omega4Q\n\nend P2qJumps\n"
open(os.path.join(os.path.dirname(outdir.rstrip("/")), "Kernel.lean"), "w").write(glue)
print(len(chunks), len(names))
